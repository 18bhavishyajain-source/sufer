# arithmetic operators
print(5 + 3)  # addition
print(5 - 3)  # subtraction
print(5 * 3)  # multiplication
print(15 / 3)  # division
print(15 // 3)  # floor division
print(15 % 3)  # modulus
print(15 ** 3)  # exponentiation

# comparison operators
print(5 > 3)  # greater than
print(5 < 3)  # less than
print(5 == 3)  # equal to
print(5 != 3)  # not equal to
print(5 >= 3)  # greater than or equal to
print(5 <= 3)  # less than or equal to

# logical operators
print(True and False)  # logical AND # if both are true, then True, else False
print(True or False)   # logical OR # if either is true, then True, else False
print(not True)        # logical NOT # inverts the boolean value

# assignment operators
x = 5
print(x)  # assigns 5 to x and prints the value of x
x += 3    # equivalent to x = x + 3
print(x)  # prints the updated value of x
x -= 2    # equivalent to x = x - 2
print(x)  # prints the updated value of x
x *= 4    # equivalent to x = x * 4
print(x)  # prints the updated value of x
x /= 2    # equivalent to x = x / 2
print(x)  # prints the updated value of x