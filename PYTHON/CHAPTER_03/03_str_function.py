# string functions
a = 'chiku ji'
print(len(a)) # length of string
print(a.startswith('c')) # check if string starts with 'c'
print(a.endswith('u')) # check if string ends with 'u'
print(a.count('i')) # count the number of occurrences of 'i'
print(a.upper()) # convert string to uppercase
print(a.lower()) # convert string to lowercase
print(a.capitalize()) # capitalize the first letter of the string
print(a.title()) # capitalize the first letter of each word in the string
print(a.replace("ch","sh"))
print(a.split()) # split the string into a list of words
print(a.find('u')) # find the index of the first occurrence of 'u'
print(a.index('k')) # find the index of the first occurrence of 'k'