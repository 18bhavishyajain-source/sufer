a = "Chiku is a good girl\n AND\nShe is very beautiful"
print(a) # print the string with escape sequence

# \n is used to create a new line in the string
# \t is used to create a tab space in the string
# \\ is used to print a backslash in the string
# \" is used to print a double quote in the string
# \' is used to print a single quote in the string
# \r is used to create a carriage return in the string
# \b is used to create a backspace in the string
# \a is used to create a bell sound in the string
# \f is used to create a form feed in the string

print("chiku\rji") # print the string with carriage return 
print("chiku\baavi") # print the string with backspace
print("aavi\achiku") # print the string with bell sound
print("chiku\faavi") # print the string with form feed